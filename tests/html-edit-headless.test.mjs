import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { createServer } from 'vite';
import { chromium } from 'playwright';

test('HTML 原位编辑支持多处草稿、恢复、撤销及动态重绘', async () => {
  const server = await createServer({ configFile: false, server: { port: 0 }, plugins: [{ name:'fixture', configureServer(s) { s.middlewares.use('/__html_edit', (_req, res) => { res.setHeader('Content-Type','text/html'); res.end('<script type="module" src="/tests/html-edit-fixture.js"></script>'); }); } }] });
  await server.listen();
  const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  const browser = await chromium.launch({headless:true,...(existsSync(chrome)?{executablePath:chrome}:{})});
  try {
    const page = await browser.newPage();
    await page.goto(`${server.resolvedUrls.local[0]}__html_edit`);
    await page.waitForFunction(() => window.messages.some(m => m.type === 'ready'));
    const frame = page.frameLocator('iframe');
    await page.evaluate(() => window.sendHost('mode',{mode:'area'}));
    await frame.locator('p').first().evaluate(p=>{const range=document.createRange();range.setStart(p.firstChild,1);range.setEnd(p.firstChild,4);const r=range.getBoundingClientRect();for(const [type,x,y] of [['mousedown',r.left+.2,r.top+.2],['mousemove',r.right-.2,r.bottom-.2],['mouseup',r.right-.2,r.bottom-.2]])p.dispatchEvent(new MouseEvent(type,{bubbles:true,button:0,buttons:type==='mouseup'?0:1,clientX:x,clientY:y}))});
    await page.waitForFunction(() => window.messages.some(m=>m.type==='area-selected'));
    const selection=await page.evaluate(()=>window.messages.find(m=>m.type==='area-selected').selected);
    assert.equal(selection.quote,'一段初');
    assert.equal(selection.contentAnchor.fragments.length,1);
    assert.equal(await frame.locator('body').evaluate(()=>CSS.highlights.has('openmargin-area-draft')),true,'框选草稿高亮可见');
    await page.evaluate(()=>window.sendHost('zoom',{percent:110}));
    await page.waitForFunction(()=>window.messages.some(m=>m.type==='viewport-resized'&&m.zoom===110));
    assert.equal(await frame.locator('body').evaluate(()=>CSS.highlights.has('openmargin-area-draft')),true,'缩放后保留草稿高亮');
    await page.evaluate(()=>window.sendHost('zoom',{percent:100}));
    await page.evaluate(selection=>window.sendHost('marks',{annotations:[{id:'content-area',kind:'area',contentAnchor:selection.contentAnchor}]}),selection);
    await frame.locator('mark[data-om-area="content-area"]').waitFor();
    await page.evaluate(()=>window.sendHost('active-note',{id:'content-area'}));
    await frame.locator('mark[data-om-area="content-area"][data-om-active]').waitFor();
    await page.evaluate(()=>window.sendHost('measure-note',{id:'content-area',token:'measure'}));
    await page.waitForFunction(()=>window.messages.some(m=>m.type==='note-anchor'&&m.token==='measure'&&m.rects.length));
    await page.evaluate(()=>window.sendHost('zoom',{percent:110}));
    await frame.locator('mark[data-om-area="content-area"]').waitFor();
    await page.evaluate(()=>{window.sendHost('zoom',{percent:100});window.sendHost('clear-draft');});
    const annotations = [{id:'text',kind:'text',quote:'第一段初始文字',before:'',after:'第二段初始文字第三段初始文字'},{id:'area',kind:'area',area:{x:20,y:30,width:50,height:20,viewportWidth:700,zoom:100},validArea:true}];
    await page.evaluate(annotations => window.sendHost('marks',{annotations}), annotations);
    await frame.locator('[data-om-mark]').first().waitFor();
    await frame.locator('[data-om-area]').waitFor();
    await page.evaluate(() => window.sendHost('mode',{mode:'edit'}));
    await frame.locator('[data-om-mark]').first().waitFor({state:'detached'});
    await frame.locator('[data-om-area]').waitFor({state:'detached'});
    await page.waitForTimeout(100);
    const initialExternal=await page.evaluate(() => window.messages.filter(m => m.type === 'content-changed').length);
    const p1 = frame.locator('p').nth(0), p2 = frame.locator('p').nth(1);
    await p1.click({position:{x:20,y:8}});
    await page.keyboard.insertText('新');
    await page.waitForFunction(() => window.messages.some(m => m.type === 'edit-dirty' && m.changes.length === 1));
    assert.notEqual(await p1.textContent(),'第一段初始文字');
    const p1changed=await p1.textContent();
    assert.notEqual(p1changed,'新第一段初始文字','点击正文中间保持自然光标位置');
    await p2.click();
    await page.keyboard.insertText('改');
    await page.waitForFunction(() => window.messages.some(m => m.type === 'edit-dirty' && m.changes.length === 2));
    const draft=await page.evaluate(() => window.messages.filter(m => m.type === 'edit-dirty').at(-1).changes);
    assert.equal(draft.length,2);
    const lastInput=await page.evaluate(()=>window.messages.filter(m=>m.type==='edit-dirty').at(-1));
    assert.ok(lastInput.inputType && lastInput.groupKey,'输入类型和位置传给宿主');
    assert.ok(await page.evaluate(()=>window.messages.some(m=>m.type==='edit-group-break')),'切换段落结束输入分组');
    const replay=async(request,changes)=>{await page.evaluate(({request,changes})=>window.sendHost('edit-apply-changes',{request,changes}),{request,changes});await page.waitForFunction(request=>window.messages.some(m=>m.type==='edit-applied'&&m.request===request),request);return page.evaluate(request=>window.messages.find(m=>m.type==='edit-applied'&&m.request===request).ok,request)};
    assert.equal(await replay('undo-second',draft.slice(0,1)),true);
    assert.equal(await p2.textContent(),'第二段初始文字','撤回当前段不影响上一段');
    assert.equal(await p1.textContent(),p1changed);
    assert.equal(await replay('undo-all',[]),true);
    assert.equal(await p1.textContent(),'第一段初始文字');
    assert.equal(await replay('redo-all',draft),true);
    assert.equal(await p1.textContent(),p1changed,'可跨段重做');
    const longDraft=structuredClone(draft);
    for(const length of [10001,100000]) {
      longDraft[1].after='长'.repeat(length);
      assert.equal(await replay('long-draft-'+length,longDraft),true,`${length} 字草稿可回放`);
      assert.equal((await p2.textContent()).length,length);
    }
    longDraft[1].after='长'.repeat(100001);
    assert.equal(await replay('too-long-draft',longDraft),false,'超出上限时拒绝回放');
    assert.equal((await p2.textContent()).length,100000,'拒绝回放不破坏现有草稿');
    assert.equal(await replay('restore-short',draft),true);
    await p2.focus();
    const beforeShortcut=await p2.textContent();
    await page.keyboard.press('Control+z');
    await page.waitForFunction(()=>window.messages.some(m=>m.type==='edit-undo-shortcut'&&!m.redo));
    await page.keyboard.press('Control+Shift+z');
    await page.waitForFunction(()=>window.messages.some(m=>m.type==='edit-undo-shortcut'&&m.redo));
    assert.equal(await p2.textContent(),beforeShortcut,'键盘事件不会触发浏览器自身撤销');
    const unknown=structuredClone(draft[1]);unknown.domPath.at(-1).index+=1;unknown.before='第三段初始文字';unknown.after='不能修改未经编辑段落';
    assert.equal(await replay('untracked',[...draft,unknown]),false,'拒绝未编辑节点');
    assert.equal(await frame.locator('p').nth(2).textContent(),'第三段初始文字');
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(() => window.messages.filter(m => m.type === 'content-changed').length), initialExternal, '原位输入不应视为外部修改');
    await page.evaluate(() => window.sendHost('search',{query:'初始',index:0,scroll:false}));
    const externalBefore=await page.evaluate(() => window.messages.filter(m => m.type === 'content-changed').length);
    await page.evaluate(annotations => { window.sendHost('marks',{annotations}); window.sendHost('zoom',{percent:110}); },annotations);
    await page.waitForTimeout(150);
    assert.equal(await page.evaluate(() => window.messages.filter(m => m.type === 'content-changed').length),externalBefore,'缩放不应视为正文变更');
    assert.equal(await frame.locator('[data-om-mark],[data-om-area]').count(),0,'编辑期间不重建批注标记');
    assert.equal(await p1.textContent(),p1changed,'搜索和标注更新不覆盖草稿');
    await page.evaluate(() => window.sendHost('edit-cancel'));
    await page.waitForFunction(() => document.querySelector('iframe').contentWindow !== null);
    await p1.waitFor();
    await assert.doesNotReject(async () => { await p1.getByText('第一段初始文字').waitFor({timeout:3000}); });
    assert.equal(await p2.textContent(),'第二段初始文字');
    await page.evaluate(() => {window.sendHost('zoom',{percent:100});window.sendHost('mode',{mode:'text'});});
    await frame.locator('[data-om-mark]').first().waitFor();
    await frame.locator('[data-om-area]').waitFor();
    await page.evaluate(() => window.sendHost('mode',{mode:'edit'}));
    await frame.locator('[data-om-mark]').first().waitFor({state:'detached'});
    await page.evaluate(knownChanges => window.sendHost('edit-restore',{changes:knownChanges.slice(0,1),knownChanges,request:'restore-check'}),draft);
    await page.waitForFunction(() => window.messages.some(m => m.type === 'edit-restored' && m.ok && m.request==='restore-check'));
    assert.equal(await p1.textContent(),p1changed);
    assert.equal(await p2.textContent(),'第二段初始文字');
    assert.equal(await replay('restored-redo',draft),true,'恢复后可重做历史中已登记的其他段落');
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(() => window.messages.filter(m => m.type === 'content-changed').length), initialExternal, '取消及恢复草稿不应视为外部修改');
    // Replacing a node with the original DOM/text is a common framework redraw.
    await p1.evaluate(el => { const n = el.cloneNode(false); n.textContent='第一段初始文字'; el.replaceWith(n); });
    await page.waitForFunction(() => window.messages.filter(m => m.type === 'edit-conflict').length === 0);
    await assert.doesNotReject(async () => { for(let i=0;i<100;i++){if(await p1.textContent()===p1changed)return;await new Promise(r=>setTimeout(r,10))}throw Error('重绘后草稿未恢复'); });
    await p1.evaluate(el => { const n = el.cloneNode(false); n.textContent='外部变更'; el.replaceWith(n); });
    await page.waitForFunction(() => window.messages.some(m => m.type === 'edit-conflict'));
    assert.equal((await page.evaluate(() => window.messages.find(m=>m.type==='edit-conflict').changes)).length,2,'冲突时保留全部草稿');
    for(const length of [10001,100000]) {
      await page.evaluate(()=>window.loadDoc());
      await page.waitForFunction(()=>window.messages.some(m=>m.type==='ready'));
      await page.evaluate(()=>window.sendHost('mode',{mode:'edit'}));
      const restored=structuredClone(draft);restored[1].after='长'.repeat(length);
      await page.evaluate(({restored,length})=>window.sendHost('edit-restore',{changes:restored,knownChanges:restored,request:'restore-long-'+length}),{restored,length});
      await page.waitForFunction(length=>window.messages.some(m=>m.type==='edit-restored'&&m.request==='restore-long-'+length&&m.ok),length);
      assert.equal((await frame.locator('p').nth(1).textContent()).length,length,`${length} 字草稿可跨窗口恢复`);
    }
  } finally { await browser.close(); await server.close(); }
});
