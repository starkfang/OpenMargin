import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { createServer } from 'vite';
import { chromium } from 'playwright';

test('批注组件和大纲图标的布局及交互', async () => {
  const server = await createServer({ configFile: false, server: { port: 0, strictPort: false }, plugins: [{ name: 'component-fixture', configureServer(s) { s.middlewares.use('/__review_test', (_req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<div id="root"></div><script type="module" src="/tests/review-delete-fixture.jsx"></script>'); }); } }] });
  await server.listen();
  const systemChrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  const browser = await chromium.launch({ headless: true, ...(existsSync(systemChrome) ? { executablePath: systemChrome } : {}) });
  try {
    const page = await browser.newPage();
    await page.goto(`${server.resolvedUrls.local[0]}__review_test`);
    await page.mouse.move(900, 600);
    const del = page.getByRole('button', { name: '删除批注' });
    await del.waitFor();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.review-tools')).opacity === '0');
    const reserved = await page.locator('.review-tools').boundingBox();
    assert.equal(await del.evaluate(el => getComputedStyle(el).color), 'rgb(222, 60, 60)', '删除图标默认红色');
    assert.equal(await page.getByRole('button', { name: '编辑批注' }).evaluate(el => getComputedStyle(el).color), 'rgb(143, 149, 158)', '编辑图标默认灰色');
    await page.locator('.review-card').hover();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.review-tools')).opacity === '1');
    const visible = await page.locator('.review-tools').boundingBox();
    assert.equal(visible.width, reserved.width, '图标显示时保留相同空间');
    assert.equal(visible.x, reserved.x, '图标显示时布局不跳动');
    await page.mouse.move(900, 600);
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.review-tools')).opacity === '0');
    await del.focus();
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.review-tools')).opacity === '1');
    await assert.doesNotReject(() => page.getByRole('tooltip').getByText('删除批注').waitFor());
    assert.equal(await del.evaluate(el => getComputedStyle(el).color), 'rgb(222, 60, 60)');
    assert.equal(await del.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 240, 240)');
    const close = page.getByRole('button', { name: '关闭批注' });
    await close.focus();
    assert.equal(await close.evaluate(el => getComputedStyle(el).color), 'rgb(100, 106, 115)');
    await page.evaluate(() => window.renderDeleteTest({ disabled: true }));
    await del.focus();
    assert.equal(await del.getAttribute('aria-disabled'), 'true');
    await assert.doesNotReject(() => page.getByRole('tooltip').getByText('正在保存').waitFor());
    await del.dispatchEvent('click');
    assert.equal(await page.evaluate(() => window.deleteCalls || 0), 0);
    await page.evaluate(() => window.renderDeleteTest({ message: '删除这条批注？' }));
    const confirm = page.getByRole('button', { name: '确认' });
    assert.equal(await confirm.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(222, 60, 60)');
    await page.evaluate(() => window.renderDeleteTest({ message: '放弃修改？' }));
    assert.equal(await confirm.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(51, 112, 255)');
    for (const options of [{ variant: 'sidebar' }, { variant: 'popover' }, { composer: true, variant: 'popover' }]) {
      await page.evaluate(options => window.renderLayoutTest(options), options);
      await page.locator(options.composer ? '.review-composer' : `.review-card-${options.variant}`).waitFor();
      const input = page.getByRole('textbox');
      await input.waitFor();
      const quote = page.locator('.review-excerpt');
      const initial = await input.boundingBox();
      const excerpt = await quote.boundingBox();
      assert.ok(Math.abs(initial.x - excerpt.x) < 1 && Math.abs(initial.width - excerpt.width) < 1, '输入和引用应同宽对齐');
      await input.fill('长批注内容，'.repeat(100));
      const tall = await input.boundingBox();
      assert.ok(tall.height > initial.height, '长内容应自动撑高');
      assert.ok(await input.evaluate(el => el.scrollHeight <= el.clientHeight + 1), '内容不应被裁切');
      const actions = await page.locator('.review-actions').boundingBox();
      const actionButtons = await page.locator('.review-actions button').all();
      const last = await actionButtons.at(-1).boundingBox();
      assert.ok(Math.abs(actions.x + actions.width - last.x - last.width) < 1, '按钮应右对齐');
      assert.ok(actions.y > excerpt.y && actions.y > tall.y, '按钮应在内容之后');
      await page.evaluate(() => { window.submitCalls = 0; });
      await input.fill('  ');
      await input.press('Enter');
      assert.equal(await page.evaluate(() => window.submitCalls), 0, '空白内容不提交');
      await input.fill('第一行');
      await input.press('End');
      await input.press('Shift+Enter');
      await input.pressSequentially('第二行');
      assert.equal(await input.inputValue(), '第一行\n第二行', 'Shift+Enter 换行');
      await input.dispatchEvent('keydown', { key:'Enter', keyCode:229, isComposing:true, bubbles:true });
      assert.equal(await page.evaluate(() => window.submitCalls), 0, '输入法组合期间不提交');
      await input.dispatchEvent('keydown', { key:'Enter', keyCode:229, bubbles:true });
      assert.equal(await page.evaluate(() => window.submitCalls), 0, 'keyCode 229 不提交');
      await input.dispatchEvent('compositionstart', { data:'拼音', bubbles:true });
      await input.dispatchEvent('keydown', { key:'Enter', keyCode:13, bubbles:true });
      await input.dispatchEvent('compositionend', { data:'拼音', bubbles:true });
      assert.equal(await page.evaluate(() => window.submitCalls), 0, '组合输入状态不提交');
      await input.press('Enter');
      assert.equal(await page.evaluate(() => window.submitCalls), 1, 'Enter 提交');
      assert.equal(await input.inputValue(), '第一行\n第二行', '提交后组件本身不清空草稿');
      if (!options.composer) {
        const meta = page.locator('.review-meta').first();
        assert.equal(await meta.evaluate(el => getComputedStyle(el).color), 'rgb(100, 106, 115)');
        const missing = page.getByText('无法定位', {exact:true});
        assert.ok(await missing.isVisible());
        assert.equal(await missing.evaluate(el => getComputedStyle(el).color), 'rgb(162, 82, 0)');
      }
    }
    const areaCases = [
      { quote: '旧区域里的文字', kind: 'area', active: true, expected: '已框选区域（中心附近：旧区域里的文字）' },
      { quote: '已框选区域（中心附近：现有摘要）', kind: 'area', expected: '已框选区域（中心附近：现有摘要）' },
      { quote: '', kind: 'area', expected: '已框选区域' },
      { quote: '普通文本', kind: 'text', expected: '普通文本' },
    ];
    for (const item of areaCases) {
      await page.evaluate(item => window.renderAreaTest(item), item);
      const excerpt = page.locator('.review-excerpt');
      await excerpt.waitFor();
      await page.waitForFunction(expected => document.querySelector('.review-excerpt')?.textContent === expected, item.expected);
      assert.equal(await page.evaluate(() => window.testAnnotation.quote), item.quote, '历史数据不应被修改');
      assert.equal(await page.locator('.review-card').getAttribute('aria-current'), item.active ? 'true' : null);
      assert.equal(await page.locator('.review-card').evaluate(el => el.classList.contains('review-card-active')), !!item.active);
      assert.equal(await page.locator('.review-location-hint').count(), 0, '选中批注不显示冗余提示');
    }
    await page.evaluate(() => window.renderActivationTest());
    const card = page.locator('.review-card');
    await card.waitFor();
    await card.click({ position: { x: 10, y: 10 } });
    assert.equal(await page.evaluate(() => window.activateCalls), 1, '卡片空白点击选中');
    await card.focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => window.activateCalls), 2, '键盘选中卡片');
    await page.getByRole('button', { name: '引用正文' }).click();
    assert.equal(await page.evaluate(() => window.quoteCalls), 1, '引用保留独立点击');
    assert.equal(await page.evaluate(() => window.activateCalls), 2, '引用点击不重复激活');
    await page.getByRole('button', { name: '编辑批注' }).click();
    assert.equal(await page.evaluate(() => window.activateCalls), 2, '卡片内按钮不激活卡片');
    await page.evaluate(() => window.renderOutlineFixture());
    const toggle = page.locator('.outline-toggle');
    await toggle.waitFor();
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    const toggleBox = await toggle.boundingBox();
    const iconBox = await toggle.locator('svg').boundingBox();
    const spacerBox = await page.locator('.outline-spacer').boundingBox();
    assert.equal(toggleBox.width, 24);
    assert.equal(spacerBox.width, 24);
    assert.equal(iconBox.width, 15);
    assert.equal(iconBox.height, 15);
    assert.ok(Math.abs(iconBox.y + iconBox.height / 2 - toggleBox.y - toggleBox.height / 2) < 1, '大纲图标垂直居中');
    await toggle.focus();
    await page.keyboard.press('Enter');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await page.getByRole('button', {name: '叶节点'}).count(), 0);
    await page.keyboard.press('Space');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    assert.equal(await page.getByRole('button', {name: '叶节点'}).count(), 1);
    for (const variant of ['sidebar','popover']) {
      await page.evaluate(variant => window.renderMissingTest({variant, missing:true}), variant);
      const row=page.locator(`.review-card-${variant} .review-meta-row`);
      await row.waitFor();
      const status=row.getByText('无法定位',{exact:true});
      const statusRect=await status.boundingBox(), metaRect=await row.locator('.review-meta').boundingBox(), rowRect=await row.boundingBox();
      assert.ok(statusRect.x >= metaRect.x+metaRect.width, '失联状态在元信息右侧');
      assert.ok(Math.abs(statusRect.x+statusRect.width-rowRect.x-rowRect.width)<1, '失联状态右对齐');
      assert.ok(await status.evaluate(el=>el.scrollWidth<=el.clientWidth), '失联状态不截断');
      const times=row.locator('.review-time');
      assert.equal(await times.count(),1);
      assert.equal(await times.textContent(),'2026/10/30 09:12:34');
      assert.equal(await times.getAttribute('aria-label'),'创建：2026/10/29 08:30:56\n修改：2026/10/30 09:12:34');
      await times.focus();
      await page.getByRole('tooltip').getByText(/创建：2026\/10\/29 08:30:56/).waitFor();
      assert.equal(await page.locator('.review-excerpt').textContent(),'一段很长的引用原文用于检查截断和提示');
      for (const updatedAt of [null,'not-a-date']) {
        await page.evaluate(([variant,updatedAt]) => window.renderMissingTest({variant,missing:true,updatedAt}), [variant,updatedAt]);
        const time=page.locator(`.review-card-${variant} .review-time`);
        assert.equal(await time.count(),1);
        assert.equal(await time.textContent(),'2026/10/29 08:30:56');
        assert.equal(await time.getAttribute('aria-label'),'创建：2026/10/29 08:30:56');
      }
      await page.evaluate(variant => window.renderMissingTest({variant, missing:false}), variant);
      await page.waitForFunction(() => !document.querySelector('.review-missing'));
    }
    for (const variant of ['sidebar','popover']) {
      await page.evaluate(variant => window.renderFloatingTest({variant}), variant);
      const card=page.locator(`.review-card-${variant}`);
      await card.waitFor();
      const geometry=() => card.evaluate(el=>{const body=el.querySelector('.review-body'),range=document.createRange();range.selectNodeContents(body);const r=body.getBoundingClientRect(),c=el.getBoundingClientRect();return {width:r.width,height:c.height,lines:[...range.getClientRects()].map(x=>({width:x.width,top:x.top}))}});
      await page.mouse.move(900,600);
      const hidden=await geometry();
      await card.hover();
      await page.waitForFunction(()=>getComputedStyle(document.querySelector('.review-tools')).opacity==='1');
      const shown=await geometry();
      assert.deepEqual(shown,hidden,`${variant} 悬浮操作不改变正文宽度、换行及卡片高度`);
      const layout=await card.evaluate(el=>{const tool=el.querySelector('.review-tools').getBoundingClientRect(),box=el.getBoundingClientRect(),body=el.querySelector('.review-body').getBoundingClientRect(),buttons=[...el.querySelectorAll('.review-tools button')];const first=buttons[0].getBoundingClientRect(),second=buttons[1].getBoundingClientRect();return {inside:tool.top>=box.top&&tool.right<=box.right,overlap:body.right>tool.left&&body.left<tool.right&&body.bottom>tool.top&&body.top<tool.bottom,separated:first.right<second.left,borders:buttons.map(button=>getComputedStyle(button).borderTopWidth)}});
      assert.ok(layout.inside,`${variant} 操作按钮位于卡片内部`);
      assert.equal(layout.overlap,false,`${variant} 操作按钮不遮挡正文`);
      assert.ok(layout.separated,`${variant} 按钮有独立间距`);
      assert.deepEqual(layout.borders,['1px','1px'],`${variant} 按钮有独立边框`);
      if(variant==='popover') {
        const control=await card.getByRole('button',{name:'删除批注'}).boundingBox();
        const container=await page.locator('.annotation-popover').boundingBox();
        assert.ok(control.y>=container.y&&control.y+control.height<=container.y+container.height,'浮窗操作不被滚动容器裁剪');
      }
    }
    const longQuote='这是一段需要实际测量才能知道是否被截断的引用原文';
    await page.evaluate(quote => window.renderExcerptWidthTest(quote),longQuote);
    const measuredQuote=page.locator('.review-excerpt');
    await page.waitForFunction(()=>{const el=document.querySelector('.review-excerpt');return el&&el.scrollWidth>el.clientWidth});
    await measuredQuote.focus();
    await page.getByRole('tooltip').getByText(longQuote).waitFor();
    await page.evaluate(()=>document.querySelector('#excerpt-width-fixture').style.width='900px');
    await page.waitForFunction(()=>{const el=document.querySelector('.review-excerpt');return el.scrollWidth<=el.clientWidth});
    await page.getByRole('tooltip').getByText(longQuote).waitFor({state:'detached'});
    await measuredQuote.blur();
    await measuredQuote.focus();
    await page.waitForTimeout(400);
    assert.equal(await page.getByRole('tooltip').count(),0,'完整展示的引用不重复浮出提示');
    await page.evaluate(()=>document.querySelector('#excerpt-width-fixture').style.width='150px');
    await page.waitForFunction(()=>{const el=document.querySelector('.review-excerpt');return el.scrollWidth>el.clientWidth});
    await measuredQuote.blur();
    await measuredQuote.focus();
    await page.getByRole('tooltip').getByText(longQuote).waitFor();
    await page.evaluate(() => window.renderSidebarTest(null));
    await page.getByRole('button',{name:'记录 —'}).waitFor();
    await page.getByRole('button',{name:'记录 —'}).click();
    await page.getByText('正在加载修改记录…').waitFor();
    const entries=[{time:'2026-10-29 10:00:00',before:'旧文'.repeat(300),after:'新文'.repeat(300)},{time:'2026-10-30 10:00:00',before:'前',after:'后'}];
    await page.evaluate(entries => window.renderSidebarTest(entries),entries);
    const commentsButton=page.getByRole('button',{name:'批注 2'}), historyButton=page.getByRole('button',{name:'记录 2'});
    await historyButton.waitFor();
    assert.equal(await page.locator('.toolbar').evaluate(el=>el.getBoundingClientRect().height),44);
    assert.equal(await historyButton.evaluate(el=>el.getBoundingClientRect().height),30);
    assert.equal(await page.locator('.zoom-controls').evaluate(el=>el.getBoundingClientRect().height),30);
    assert.equal(await page.locator('.search').evaluate(el=>el.getBoundingClientRect().height),30);
    await commentsButton.click();
    assert.equal(await commentsButton.getAttribute('aria-pressed'),'true');
    await historyButton.click();
    assert.equal(await historyButton.getAttribute('aria-pressed'),'true');
    const historyEntries=page.locator('.history-entry');
    assert.equal(await historyEntries.count(),2);
    assert.equal(await historyEntries.first().locator('.history-heading-meta time').textContent(),'2026-10-30 10:00:00','记录倒序');
    assert.equal(await historyEntries.first().locator('.history-kind').textContent(),'正文修改');
    assert.equal(await historyEntries.first().locator('.history-heading-section').count(),0,'没有章节时不虚构');
    assert.equal(await historyEntries.first().locator('.history-before').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 241, 241)');
    assert.equal(await historyEntries.first().locator('.history-after').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(237, 249, 240)');
    const old=historyEntries.nth(1),before=old.locator('.history-change').first().locator('p');
    assert.ok((await before.textContent()).length<=161,'整篇替换时摘要限制长度');
    await old.getByRole('button',{name:'查看详情'}).click();
    assert.equal(await page.evaluate(()=>window.historyPreviewEntry.time),'2026-10-29 10:00:00','查看详情传递该记录');
    await historyButton.click();
    assert.equal(await page.locator('.comments').isVisible(),false,'点击当前项收起');
    await page.evaluate(() => window.renderSidebarTest([]));
    await page.getByRole('button',{name:'记录 0'}).waitFor();
    const preview={before:'共享\n旧内容\n结尾',after:'共享\n新内容\n结尾',current:'共享\n当前草稿\n结尾',dirty:true,recordedAt:'2026/10/30 10:00:00'};
    await page.evaluate(preview=>window.renderHistoryDialogTest(preview),preview);
    const dialog=page.getByRole('alertdialog',{name:'修改详情'});
    await dialog.waitFor();
    assert.deepEqual(await dialog.locator('.history-compare-head strong').allTextContents(),['修改前','修改后']);
    assert.equal(await dialog.locator('.history-compare-cell.is-removed p').textContent(),'旧内容');
    assert.equal(await dialog.locator('.history-compare-cell.is-added p').textContent(),'新内容');
    const row=await dialog.locator('.history-compare-cell.is-removed').evaluate(el=>({a:el.getBoundingClientRect().height,b:el.nextElementSibling.getBoundingClientRect().height}));
    assert.equal(row.a,row.b,'差异行高度随内容对齐');
    assert.ok(row.a<62,'短内容不强制大行高');
    await dialog.getByRole('button',{name:'完整正文'}).click();
    assert.equal(await dialog.locator('.history-compare-cell p').filter({hasText:'共享'}).count(),2);
    await dialog.getByRole('button',{name:'恢复到修改前…'}).click();
    const restore=page.getByRole('alertdialog',{name:'确认恢复正文'});
    assert.deepEqual(await restore.locator('.history-compare-head strong').allTextContents(),['当前正文 · 含未保存修改','恢复后']);
    assert.equal(await restore.locator('.history-compare-cell.is-removed p').textContent(),'当前草稿');
    assert.equal(await restore.locator('.history-compare-cell.is-added p').textContent(),'旧内容');
    assert.match(await restore.locator('.history-dialog-warning').textContent(),/未保存内容.*批注保留/);
    await restore.getByRole('button',{name:'返回详情'}).click();
    await dialog.getByRole('button',{name:'恢复到修改前…'}).click();
    await restore.getByRole('button',{name:'恢复到草稿'}).click();
    assert.equal(await page.evaluate(()=>window.historyDialogRestored),true);
    await page.evaluate(preview=>window.renderHistoryDialogTest({...preview,unmapped:true}),preview);
    await page.getByRole('alertdialog',{name:'修改详情'}).getByRole('button',{name:'恢复到修改前…'}).click();
    assert.equal(await restore.getByRole('button',{name:'恢复到草稿'}).isDisabled(),true);
    assert.equal(await restore.locator('.history-compare-grid').count(),0,'无法完整映射时不展示错误的当前正文');
    const touch = await browser.newContext({hasTouch:true,isMobile:true});
    try {
      const touchPage=await touch.newPage();
      await touchPage.goto(`${server.resolvedUrls.local[0]}__review_test`);
      await touchPage.locator('.review-tools').waitFor();
      assert.equal(await touchPage.locator('.review-tools').evaluate(el=>getComputedStyle(el).opacity),'1','触屏设备默认显示操作');
    } finally { await touch.close(); }
  } finally { await browser.close(); await server.close(); }
});
